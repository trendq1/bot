let LANG = "uk";
try { LANG = localStorage.getItem("izidva_lang") || "uk"; } catch (e) {}
if (LANG !== "uk" && LANG !== "ru") LANG = "uk";

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.uk[key] ?? key;
  if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
  return s;
}
function setLang(l) {
  if (l !== "uk" && l !== "ru") return;
  LANG = l;
  try { localStorage.setItem("izidva_lang", l); } catch (e) {}
  location.reload();
}
function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-html]").forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  const head = document.getElementById("calHead");
  if (head) head.innerHTML = t("weekdays").map((d) => `<span>${d}</span>`).join("");
}
